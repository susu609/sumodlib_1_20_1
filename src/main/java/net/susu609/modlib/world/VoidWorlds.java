package net.susu609.modlib.world;

import net.minecraft.core.BlockPos;
import net.minecraft.core.registries.Registries;
import net.minecraft.resources.ResourceKey;
import net.minecraft.server.MinecraftServer;
import net.minecraft.server.level.ServerLevel;
import net.minecraft.world.level.GameRules;
import net.minecraft.world.level.Level;
import net.minecraft.world.level.block.Blocks;
import net.minecraft.world.level.block.state.BlockState;
import net.minecraft.world.level.dimension.DimensionType;
import net.minecraft.world.level.levelgen.FlatLevelSource;
import net.minecraft.world.level.levelgen.flat.FlatLayerInfo;
import net.minecraft.world.level.levelgen.presets.WorldPreset;
import net.susu609.modlib.SuModLib;
import net.susu609.modlib.resource.RL;

/**
 * Empty ("void") worlds and dimensions.
 *
 * <ul>
 * <li>World type <b>Void</b> ({@link #PRESET}): pick it on the Create World
 * screen, or {@code level-type=sumodlib:void} in server.properties. The
 * overworld is empty apart from a small stone platform at the spawn; the
 * Nether and the End stay vanilla.</li>
 * <li>Void dimensions for a mod: add
 * {@code data/<modid>/dimension/<name>.json} with {@code "type":
 * "sumodlib:void"} ({@link #DIMENSION_TYPE}: noon forever, no beds) and the
 * flat void generator (see the README), then get the level with
 * {@link #level}.</li>
 * </ul>
 */
public final class VoidWorlds {
    public static final ResourceKey<WorldPreset> PRESET = ResourceKey.create(
            Registries.WORLD_PRESET, RL.of(SuModLib.MOD_ID, "void"));
    public static final ResourceKey<DimensionType> DIMENSION_TYPE =
            ResourceKey.create(Registries.DIMENSION_TYPE,
                    RL.of(SuModLib.MOD_ID, "void"));
    /** Height of the spawn platform's top face. */
    public static final int PLATFORM_Y = 64;
    public static final int PLATFORM_RADIUS = 2;

    private VoidWorlds() {
    }

    /** Key of a mod's dimension, e.g. {@code dimension("royalarena", "arena")}. */
    public static ResourceKey<Level> dimension(String namespace, String path) {
        return ResourceKey.create(Registries.DIMENSION, RL.of(namespace, path));
    }

    /** The level for {@code key}, or the overworld when it does not exist. */
    public static ServerLevel level(MinecraftServer server,
            ResourceKey<Level> key)
    {
        ServerLevel level = server.getLevel(key);
        return level != null ? level : server.overworld();
    }

    /** Whether the level is generated by the flat generator with only air. */
    public static boolean isVoid(ServerLevel level) {
        if (!(level.getChunkSource().getGenerator() instanceof
                FlatLevelSource flat))
            return false;
        for (FlatLayerInfo layer : flat.settings().getLayersInfo()) {
            if (!layer.getBlockState().isAir())
                return false;
        }
        return true;
    }

    /**
     * Places a square platform of {@code block} with its top face at
     * {@code center}'s Y, unless the centre block is already solid. Returns
     * the position to stand on.
     */
    public static BlockPos ensurePlatform(ServerLevel level, BlockPos center,
            int radius, BlockState block)
    {
        if (level.getBlockState(center).isAir()) {
            for (int dx = -radius; dx <= radius; dx++) {
                for (int dz = -radius; dz <= radius; dz++)
                    level.setBlockAndUpdate(center.offset(dx, 0, dz), block);
            }
        }
        return center.above();
    }

    /** The default spawn platform: 5x5 stone at (0, 64, 0). */
    public static BlockPos ensureSpawnPlatform(ServerLevel level) {
        return ensurePlatform(level, new BlockPos(0, PLATFORM_Y, 0),
                PLATFORM_RADIUS, Blocks.STONE.defaultBlockState());
    }

    /**
     * Quiet rules for an empty test world: fixed noon, no weather, no
     * natural mob spawning (mods can still spawn their own mobs).
     */
    public static void applyQuietRules(GameRules rules,
            MinecraftServer server)
    {
        rules.getRule(GameRules.RULE_DAYLIGHT).set(false, server);
        rules.getRule(GameRules.RULE_WEATHER_CYCLE).set(false, server);
        rules.getRule(GameRules.RULE_DOMOBSPAWNING).set(false, server);
    }
}
